// Package tui 实现终端用户界面（Terminal User Interface）。
//
// 基于 bubbletea 框架的 Elm Architecture：
//   - Model：存储界面状态（消息列表、输入框内容、Agent 状态）
//   - Update：处理事件（用户输入、LLM 流式输出、工具执行结果）
//   - View：渲染界面（消息区 + 状态栏 + 输入框）
//
// 界面分三个区域：
//
//	┌─────────────────────────┐
//	│  消息滚动区（viewport）   │  ← 对话历史 + LLM 流式输出
//	├─────────────────────────┤
//	│  状态栏                  │  ← 模型名、token 消耗、Agent 状态
//	├─────────────────────────┤
//	│  输入框（textinput）      │  ← 用户输入
//	└─────────────────────────┘
package tui
